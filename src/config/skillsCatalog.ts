/**
 * Filter skills by category. If category is 'all', returns the full catalog.
 */
export function getSkillsByCategory(category: SkillCategory): SkillItem[] {
  if (category === 'all') {
    return SKILLS_SH_CATALOG;
  }
  return SKILLS_SH_CATALOG.filter((item) => item.category === category);
}

/**
 * Returns all skills verified with the official maker badge.
 */
export function getOfficialSkills(): SkillItem[] {
  return SKILLS_SH_CATALOG.filter((item) => item.isOfficial === true);
}

/**
 * Filter skills by source type ('skills.sh' | 'github' | 'local').
 */
export function getSkillsBySource(sourceType: SkillSourceType): SkillItem[] {
  return SKILLS_SH_CATALOG.filter((item) => item.sourceType === sourceType);
}

/**
 * Returns top trending skills sorted by install count.
 */
export function getTrendingSkills(limit: number = 10): SkillItem[] {
  return [...SKILLS_SH_CATALOG]
    .sort((a, b) => (b.installs ?? 0) - (a.installs ?? 0))
    .slice(0, limit);
}

/**
 * Looks up a single skill by ID or slug.
 */
export function getSkillById(idOrSlug: string): SkillItem | undefined {
  const normalized = idOrSlug.toLowerCase();
  return SKILLS_SH_CATALOG.find(
    (item) =>
      item.id.toLowerCase() === normalized ||
      (item.slug && item.slug.toLowerCase() === normalized)
  );
}

export interface SearchSkillsCatalogOptions {
  category?: SkillCategory;
  onlyInstalled?: boolean;
  onlyOfficial?: boolean;
  source?: SkillSourceType;
}

/**
 * Multi-dimensional search across title, name, slug, description, triggers,
 * tags, repo, owner, and author with category and status filtering.
 */
export function searchSkillsCatalog(
  query: string,
  options?: SearchSkillsCatalogOptions
): SkillItem[] {
  const trimmed = query.trim().toLowerCase();

  return SKILLS_SH_CATALOG.filter((item) => {
    // Category filter
    if (options?.category && options.category !== 'all' && item.category !== options.category) {
      return false;
    }

    // Installed status filter
    if (options?.onlyInstalled !== undefined && item.isInstalled !== options.onlyInstalled) {
      return false;
    }

    // Official badge filter
    if (options?.onlyOfficial && !item.isOfficial) {
      return false;
    }

    // Source type filter
    if (options?.source && item.sourceType !== options.source) {
      return false;
    }

    // Empty query matches all items passing previous filters
    if (trimmed === '') {
      return true;
    }

    // Search query matches across multiple dimensions
    const titleMatch = item.title.toLowerCase().includes(trimmed);
    const nameMatch = item.name.toLowerCase().includes(trimmed);
    const slugMatch = item.slug ? item.slug.toLowerCase().includes(trimmed) : false;
    const descMatch = item.description.toLowerCase().includes(trimmed);
    const authorMatch = item.author.toLowerCase().includes(trimmed);
    const ownerMatch = item.owner ? item.owner.toLowerCase().includes(trimmed) : false;
    const repoMatch = item.repo ? item.repo.toLowerCase().includes(trimmed) : false;
    const tagMatch = item.tags.some((t) => t.toLowerCase().includes(trimmed));
    const triggerMatch = item.triggers
      ? item.triggers.some((tr) => tr.toLowerCase().includes(trimmed))
      : false;

    return (
      titleMatch ||
      nameMatch ||
      slugMatch ||
      descMatch ||
      authorMatch ||
      ownerMatch ||
      repoMatch ||
      tagMatch ||
      triggerMatch
    );
  });
}

