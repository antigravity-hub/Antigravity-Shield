def build():
    en_tree, en_flat = load_en()
    _, ko_flat = load_locale('ko')

    combined_dict = dict(ko_flat)
    combined_dict.update(KO_TRANSLATIONS)

    final_dict = {}
    for k, v in combined_dict.items():
        if k in en_flat:
            en_val = en_flat[k]
            if v.strip() != en_val.strip() or en_val.strip() in TECHNICAL_INVARIANTS:
                final_dict[k] = v

    return sync_and_write('ko', final_dict)

if __name__ == '__main__':
    build()
