VAR_FIXES = {
    "proxy.cli_sync.toast.sync_error": "Senkronizasyon başarısız: {{error}}"
}

def build():
    en_tree, en_flat = load_en()
    _, tr_flat = load_locale('tr')

    combined_dict = dict(tr_flat)
    combined_dict.update(TR_TRANSLATIONS)

    final_dict = {}
    for k, v in combined_dict.items():
        if k in en_flat:
            en_val = en_flat[k]
            if v.strip() != en_val.strip() or en_val.strip() in TECHNICAL_INVARIANTS:
                final_dict[k] = v

    return sync_and_write('tr', final_dict, VAR_FIXES)

if __name__ == '__main__':
    build()
