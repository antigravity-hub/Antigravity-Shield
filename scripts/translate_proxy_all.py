def set_deep(d, path, val):
    parts = path.split('.')
    cur = d
    for p in parts[:-1]:
        if p not in cur or not isinstance(cur[p], dict):
            cur[p] = {}
        cur = cur[p]
    cur[parts[-1]] = val

for lang, mapping in [('fa', FA_PROXY_TRANSLATIONS), ('tr', TR_EXTRA_TRANSLATIONS)]:
    filepath = f'src/locales/{lang}.json'
    with open(filepath, 'r', encoding='utf-8') as f:
        data = json.load(f)
    
    updated = 0
    for key, translation in mapping.items():
        set_deep(data, key.strip(), translation)
        updated += 1
    
    with open(filepath, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
    print(f'Updated {updated} keys in {filepath}')
